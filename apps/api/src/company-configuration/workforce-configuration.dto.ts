const mobileMessage = {
  message: "Enter a UAE mobile number, for example 0506468442 or 9715XXXXXXXX.",
};

/**
 * Employee is the master workforce entity. Its role (Customer Service, Driver,
 * ...) is chosen from the configurable list. When the role is a driver role the
 * engagement decides compensation: "employee" is salaried with allowances,
 * "outsourced" has no salary and a fixed fee per delivered order. The Employee
 * number is backend-generated and never submitted.
 */
export class SaveEmployeeDto {
  @IsUUID()
  public readonly employeeRoleId!: string;

  @IsOptional()
  @IsIn(["employee", "outsourced"])
  public readonly engagement?: "employee" | "outsourced";

  @IsOptional()
  @IsNumber()
  @Min(0)
  public readonly outsourcedFeePerDeliveredOrder?: number;

  @IsString()
  @MaxLength(160)
  public readonly name!: string;

  @NormalizeUaeMobile()
  @Matches(mobilePattern, mobileMessage)
  public readonly mobileNumber!: string;

  @IsOptional()
  @NormalizeUaeMobile()
  @Matches(mobilePattern, mobileMessage)
  public readonly secondMobileNumber?: string;

  @IsOptional()
  @IsEmail()
  @MaxLength(160)
  public readonly email?: string;

  @IsOptional()
  @IsString()
  @MaxLength(300)
  public readonly address?: string;

  @IsOptional()
  @IsUUID()
  public readonly areaId?: string;

  @IsOptional()
  @IsDateString()
  public readonly dateOfBirth?: string;

  @IsOptional()
  @IsString()
  @MaxLength(100)
  public readonly nationality?: string;

  @IsOptional()
  @IsDateString()
  public readonly joiningDate?: string;

  @IsOptional()
  @IsString()
  @MaxLength(120)
  public readonly jobTitle?: string;

  @IsOptional()
  @IsString()
  @MaxLength(120)
  public readonly department?: string;

  @IsOptional()
  @IsString()
  @MaxLength(80)
  public readonly employeeType?: string;

  @IsOptional()
  @IsNumber()
  @Min(0)
  public readonly basicSalary?: number;

  @IsOptional()
  @IsBoolean()
  public readonly payrollEligible?: boolean;

  @IsOptional()
  @IsBoolean()
  public readonly salaryHold?: boolean;

  @IsOptional()
  @IsString()
  @MaxLength(500)
  public readonly salaryHoldReason?: string;

  @IsOptional()
  @IsDateString()
  public readonly salaryHoldFrom?: string;

  @IsOptional()
  @IsDateString()
  public readonly salaryHoldTo?: string;

  @IsOptional()
  @IsDateString()
  public readonly salaryEffectiveFrom?: string;

  @IsOptional()
  @IsUUID()
  public readonly userId?: string;

  @IsOptional()
  @IsString()
  @MaxLength(1000)
  public readonly notes?: string;

  @IsOptional()
  @IsArray()
  @ArrayMaxSize(4)
  @ValidateNested({ each: true })
  @Type(() => EmployeeAllowanceDto)
  public readonly allowances?: EmployeeAllowanceDto[];
}

