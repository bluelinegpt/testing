/**
 * The unified Driver form. There is no separate Employee entity in the UI:
 *   driverType "employee"   -> salaried, with optional allowances (a backing
 *                              Employee record is created behind the scenes so
 *                              payroll keeps working)
 *   driverType "outsourced" -> no salary, only a fixed fee per delivered order
 *
 * The Driver code and the backing Employee number are generated by the backend;
 * neither is entered here.
 */
export class SaveDriverDto {
  @IsString()
  @MaxLength(160)
  public readonly name!: string;

  @IsIn(["employee", "outsourced"])
  public readonly driverType!: "employee" | "outsourced";

  @NormalizeUaeMobile()
  @Matches(mobilePattern, {
    message: "Enter a UAE mobile number, for example 0506468442 or 9715XXXXXXXX.",
  })
  public readonly mobileNumber!: string;

  @IsOptional()
  @NormalizeUaeMobile()
  @Matches(mobilePattern, {
    message: "Enter a UAE mobile number, for example 0506468442 or 9715XXXXXXXX.",
  })
  public readonly secondMobileNumber?: string;

  @IsOptional()
  @IsEmail()
  @MaxLength(160)
  public readonly email?: string;

  @IsOptional()
  @IsString()
  @MaxLength(300)
  public readonly address?: string;

  @IsOptional()
  @IsUUID()
  public readonly areaId?: string;

  @IsOptional()
  @IsUUID()
  public readonly vehicleId?: string;

  @IsOptional()
  @IsUUID()
  public readonly thirdPartyCompanyId?: string;

  @IsOptional()
  @IsUUID()
  public readonly userId?: string;

  @IsOptional()
  @IsString()
  @MaxLength(1000)
  public readonly notes?: string;

  // --- Employee-type compensation (salary + allowances) --------------------
  @IsOptional()
  @IsNumber()
  @Min(0)
  public readonly basicSalary?: number;

  @IsOptional()
  @IsDateString()
  public readonly salaryEffectiveFrom?: string;

  @IsOptional()
  @IsString()
  @MaxLength(120)
  public readonly jobTitle?: string;

  @IsOptional()
  @IsString()
  @MaxLength(120)
  public readonly department?: string;

  @IsOptional()
  @IsArray()
  @ArrayMaxSize(4)
  @ValidateNested({ each: true })
  @Type(() => EmployeeAllowanceDto)
  public readonly allowances?: EmployeeAllowanceDto[];

  // --- Outsourced-type compensation (fixed fee per delivered order) ---------
  @IsOptional()
  @IsNumber()
  @Min(0)
  public readonly outsourcedFeePerDeliveredOrder?: number;
}

